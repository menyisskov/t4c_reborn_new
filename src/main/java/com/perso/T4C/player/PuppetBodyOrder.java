  public static BodyPart[] getBodyPartsOrder(String angle) {
    return getBodyPartsOrder(angle, false, false, false, 0);
  }

  public static BodyPart[] getBodyPartsOrder(String angle, boolean ranged) {
    return getBodyPartsOrder(angle, false, ranged, false, 0);
  }

  public static BodyPart[] getBodyPartsOrder(
      String angle, boolean flipX, boolean ranged, boolean attacking, int frame) {
    int direction = angleToDirection(angle, flipX);
    int[][][] table =
        attacking ? (ranged ? BODY_ORDER_AR : BODY_ORDER_A) : (ranged ? BODY_ORDER_R : BODY_ORDER);
    int maxFrame = attacking ? 9 : 13;
    int selectedFrame = Math.max(0, Math.min(frame, maxFrame - 1));
    BodyPart[] result = new BodyPart[19];
    for (int slot = 0; slot < result.length; slot++) {
      result[slot] = INDEX_TO_BODY_PART[table[direction][slot][selectedFrame]];
    }
    return result;
  }

  public static int angleToDirection(String angle, boolean flipX) {
    String effective = mirroredAngle(angle, flipX);
    return switch (effective) {
      case "045" -> 1;
      case "000" -> 2;
      case "315" -> 3;
      case "090" -> 4;
      case "270" -> 6;
      case "135" -> 7;
      case "180" -> 8;
      case "225" -> 9;
      default -> 2;
    };
  }

  private static String mirroredAngle(String angle, boolean flipX) {
    if (!flipX) return angle;
    return switch (angle) {
      case "045" -> "315";
      case "315" -> "045";
      case "090" -> "270";
      case "270" -> "090";
      case "135" -> "225";
      case "225" -> "135";
      default -> angle;
    };
  }

  private static void fill(
      int[][][] table, int direction, int fromFrame, int toFrame, int... order) {
    if (order.length != 19)
      throw new IllegalArgumentException("Original body order must contain 19 slots");
    for (int frame = fromFrame; frame < toFrame; frame++) {
      for (int slot = 0; slot < order.length; slot++) table[direction][slot][frame] = order[slot];
    }
  }
