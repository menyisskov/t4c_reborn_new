  private RetiredItems() {}

  public static boolean isRetired(String key) {
    return key != null && KEYS.contains(ItemDefinition.normalizeKey(key));
  }

  /** Clear old save references before equipment bonuses and collection goals are restored. */
  public static void synchronize(Player player) {
    player.getInventory().removeIf(RetiredItems::isRetired);
    player.getEquippedItems().values().removeIf(RetiredItems::isRetired);
    player.getItemCharges().keySet().removeIf(RetiredItems::isRetired);
    removeFromStorage(player.getStorage(), player.getStorageCharges());
    if (player.getQuickSlots() != null)
      player.getQuickSlots().removeIf(slot -> slot != null && isRetired(slot.getItem()));
    if (player.getMacros() != null)
      player.getMacros().removeIf(macro -> macro != null && isRetired(macro.getItemKey()));
  }

  /** Remove item instances and their charges together, preserving every surviving association. */
  static void removeFromStorage(List<String> items, List<Integer> charges) {
    while (charges.size() < items.size()) charges.add(-1);
    while (charges.size() > items.size()) charges.remove(charges.size() - 1);
    for (int i = items.size() - 1; i >= 0; i--) {
      if (!isRetired(items.get(i))) continue;
      items.remove(i);
      charges.remove(i);
    }
  }
