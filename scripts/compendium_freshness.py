"""Stamp and verify the static compendium snapshot without changing an unchanged date."""

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import struct


def fingerprint(site):
    files = [site / "data.js"] + sorted(
        (p for p in (site / "data").rglob("*") if p.is_file()),
        key=lambda p: p.relative_to(site).as_posix())
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.relative_to(site).as_posix().encode())
        digest.update(b"\0")
        content = path.read_bytes()
        if path.suffix in {".json", ".js"}:
            content = content.replace(b"\r\n", b"\n")
        digest.update(hashlib.sha256(content).digest())
    return digest.hexdigest()


def stamp(site):
    checksum = fingerprint(site)
    path = site / "publication.json"
    previous = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    if previous.get("dataSha256") == checksum:
        publication = previous
    else:
        publication = {"generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                       "dataSha256": checksum}
    path.write_text(json.dumps(publication, indent=2) + "\n", encoding="utf-8")
    (site / "publication.js").write_text(
        "// Generated by scripts/compendium_freshness.py\nwindow.T4C_PUBLICATION = "
        + json.dumps(publication, indent=2) + ";\n", encoding="utf-8")
    return publication


def verify(site):
    publication = json.loads((site / "publication.json").read_text(encoding="utf-8"))
    if publication["dataSha256"] != fingerprint(site):
        raise ValueError("Reference data changed without refreshing its publication stamp")
    js = (site / "publication.js").read_text(encoding="utf-8")
    if json.loads(js[js.index("= ") + 2:js.rindex(";")]) != publication:
        raise ValueError("Publication JSON and browser bundle differ")
    js = (site / "data.js").read_text(encoding="utf-8")
    bundle = json.loads(js[js.index("= ") + 2:js.rindex(";")])
    for key, rows in bundle.items():
        filename = {"xpCurve": "xpcurve", "statIds": "statids"}.get(key, key)
        file = site / "data" / (filename + ".json")
        if json.loads(file.read_text(encoding="utf-8")) != rows:
            raise ValueError("Browser bundle differs from " + filename + ".json")
    zones = {z["id"] for z in bundle.get("zones", [])}
    for map_ in bundle.get("maps", []):
        if map_["zoneId"] not in zones:
            raise ValueError("Map has no zone: " + map_["zoneId"])
        image = site / "data" / map_["image"]
        if struct.unpack(">II", image.read_bytes()[16:24]) != (map_["imageWidth"], map_["imageHeight"]):
            raise ValueError("Map image dimensions differ: " + map_["zoneId"])
    for monster in bundle.get("monsters", []):
        if monster.get("sprite") and not (site / "data" / monster["sprite"]).is_file():
            raise ValueError("Missing portrait: " + monster["name"])
    return publication


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("site", nargs="?", type=Path, default=Path(__file__).resolve().parents[1] / "compendium")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = verify(args.site) if args.check else stamp(args.site)
    print("Reference data refreshed " + result["generatedAt"] + " | " + result["dataSha256"])
